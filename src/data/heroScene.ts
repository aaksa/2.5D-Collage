import { z } from "zod";
import { zColor } from "@remotion/zod-types";
import { TREATMENTS } from "../shaders/card";
import { MASKS } from "../utils/masks";

// Editor-friendly schema: everything here can be tweaked in Remotion Studio.
export const imageSchema = z.object({
  src: z.string(),
  x: z.number(),
  y: z.number(),
  z: z.number(),
  scale: z.number(), // card height in world units
  rotationX: z.number(), // degrees
  rotationY: z.number(),
  rotationZ: z.number(),
  parallax: z.number(),
  opacity: z.number().optional(),
  crop: z.tuple([z.number(), z.number(), z.number(), z.number()]).optional(),
  mask: z.enum(MASKS).optional(),
  treatment: z.enum(TREATMENTS).optional(),
  contrast: z.number().optional(),
  brightness: z.number().optional(),
  border: z.number().optional(),
  shadow: z.boolean().optional(),
  microMotion: z.number().optional(),
  enterFrame: z.number().optional(),
  exitFrame: z.number().optional(),
});

export type ImageSpec = z.infer<typeof imageSchema>;

export const premiumCollageSchema = z.object({
  durationInSeconds: z.number().min(1).max(30),
  backgroundColor: zColor(),
  accentColor: zColor(),
  highlightColor: zColor(),
  subject: z.object({
    // A rigged, animated glTF/GLB (its first animation loops). When set it
    // replaces the sprite sequence below.
    model: z.string().optional(),
    heading: z.number(), // degrees; 90 walks straight to the right
    frames: z.array(z.string()).min(1),
    holdFrames: z.number().int().min(1),
    x: z.number(),
    z: z.number(),
    height: z.number(),
  }),
  images: z.array(imageSchema),
  transitionImage: z.string(),
  pathTexture: z.string(),
  title: z.string(),
  subtitle: z.string(),
  cameraIntensity: z.number().min(0).max(2),
  parallaxIntensity: z.number().min(0).max(2),
  grainAmount: z.number().min(0).max(3),
  microMotionAmount: z.number().min(0).max(3),
  motionBlurAmount: z.number().min(0).max(1),
});

export type PremiumCollageProps = z.infer<typeof premiumCollageSchema>;

